const $ = (selector, root = document) => root.querySelector(selector);
const $$ = (selector, root = document) => [...root.querySelectorAll(selector)];
const t = (key) => I18N[state.locale][key] || I18N.zh[key] || key;

function persist() {
  localStorage.setItem("muse-state", JSON.stringify({
    locale: state.locale, theme: state.theme, blur: state.blur,
    rememberProgress: state.rememberProgress, autoSubtitle: state.autoSubtitle,
    selectedSites: state.selectedSites, preview: state.preview,
    queue: state.queue, history: state.history.slice(0, 8),
  }));
}

function escapeHtml(value = "") {
  return String(value).replace(/[&<>"']/g, char => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#039;"
  })[char]);
}

function applyLocale() {
  document.documentElement.lang = state.locale === "zh" ? "zh-Hant" : "en";
  $$("[data-i18n]").forEach(node => {
    const value = t(node.dataset.i18n);
    if (node.dataset.i18n === "heroTitle") node.innerHTML = value;
    else node.textContent = value;
  });
  $$("[data-i18n-placeholder]").forEach(node => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  $(".locale-zh").classList.toggle("active", state.locale === "zh");
  $(".locale-en").classList.toggle("active", state.locale === "en");
  if (state.sites.length) renderSourceFilter();
  updateSummary();
  render();
}

function applyPreferences() {
  document.documentElement.dataset.theme = state.theme;
  document.body.classList.toggle("thumbnails-blurred", state.blur);
  $(".theme-icon").textContent = state.theme === "dark" ? "☾" : "☀";
  $("#blurSetting").checked = state.blur;
  $("#progressSetting").checked = state.rememberProgress;
  $("#subtitleSetting").checked = state.autoSubtitle;
}

function showToast(message, error = false) {
  const toast = document.createElement("div");
  toast.className = `toast${error ? " error" : ""}`;
  toast.textContent = message;
  $("#toastRegion").append(toast);
  setTimeout(() => toast.remove(), 4200);
}

async function api(path, options = {}) {
  const response = await fetch(path, {
    headers: { "Content-Type": "application/json", ...(options.headers || {}) },
    ...options,
  });
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(payload.error || `${response.status}`);
  return payload;
}

async function initialize() {
  applyPreferences();
  applyLocale();
  try {
    const [{ sites }, library] = await Promise.all([
      api("/api/sites"), api("/api/library")
    ]);
    state.sites = sites;
    state.library = library.items;
    if (!state.selectedSites.length) {
      state.selectedSites = sites.filter(site => site.recommended).map(site => site.id);
    }
    renderSitePicker();
    renderSourceFilter();
    updateCounts();
  } catch (error) {
    showToast(`Muse: ${error.message}`, true);
  }
  bindEvents();
}

function renderSitePicker() {
  $("#siteOptions").innerHTML = state.sites.map(site => `
    <label class="site-option">
      <input type="checkbox" value="${escapeHtml(site.id)}" ${state.selectedSites.includes(site.id) ? "checked" : ""}>
      <span>${escapeHtml(site.label)}</span><small>T${site.tier}</small>
    </label>
  `).join("");
  $("#siteOptions").addEventListener("change", () => {
    state.selectedSites = $$("#siteOptions input:checked").map(input => input.value);
    updateSiteSummary();
    persist();
  });
  updateSiteSummary();
}

function updateSiteSummary() {
  const count = state.selectedSites.length;
  $("#siteSummary").textContent = state.locale === "zh" ? `${count} 個搜尋來源` : `${count} search sources`;
}

function renderSourceFilter() {
  const select = $("#sourceFilter");
  select.innerHTML = `<option value="all">${t("allSources")}</option>` +
    state.sites.map(site => `<option value="${escapeHtml(site.id)}">${escapeHtml(site.label)}</option>`).join("") +
    `<option value="local">LOCAL</option>`;
  select.value = state.sourceFilter;
}

function getCurrentItems() {
  if (state.view === "preview") return state.preview;
  if (state.view === "queue") return state.queue;
  if (state.view === "library") return state.library;
  return state.results;
}

function filteredItems() {
  let items = [...getCurrentItems()];
  items = items.filter(item => {
    const haystack = [
      item.title, item.description, item.uploader,
      ...(item.tags || [])
    ].join(" ").toLocaleLowerCase();
    if (state.withinQuery && !haystack.includes(state.withinQuery.toLocaleLowerCase())) return false;
    const itemSource = item.mediaUrl ? "local" : item.site;
    if (state.sourceFilter !== "all" && itemSource !== state.sourceFilter) return false;
    const duration = Number(item.duration);
    if (state.hideUnknown && !duration) return false;
    if (state.subtitleOnly && !item.hasSubtitle) return false;
    if (state.durationFilter === "short" && !(duration > 0 && duration < 600)) return false;
    if (state.durationFilter === "medium" && !(duration >= 600 && duration < 1800)) return false;
    if (state.durationFilter === "long" && !(duration >= 1800)) return false;
    return true;
  });
  const sorters = {
    newest: (a, b) => String(b.date || b.modified || "").localeCompare(String(a.date || a.modified || "")),
    views: (a, b) => Number(b.views || 0) - Number(a.views || 0),
    durationAsc: (a, b) => Number(a.duration || Infinity) - Number(b.duration || Infinity),
    durationDesc: (a, b) => Number(b.duration || 0) - Number(a.duration || 0),
    title: (a, b) => String(a.title).localeCompare(String(b.title), state.locale === "zh" ? "zh-Hant" : "en"),
  };
  if (sorters[state.sort]) items.sort(sorters[state.sort]);
  return items;
}

function formatDuration(seconds) {
  if (!seconds) return "—";
  const value = Math.round(Number(seconds));
  const h = Math.floor(value / 3600);
  const m = Math.floor((value % 3600) / 60);
  const s = value % 60;
  return h ? `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}` : `${m}:${String(s).padStart(2, "0")}`;
}

function formatViews(value) {
  if (!value) return "";
  return new Intl.NumberFormat(state.locale === "zh" ? "zh-TW" : "en", { notation: "compact" }).format(value);
}

function mediaKey(item) {
  return item.url || item.mediaUrl || item.id;
}

function cardHtml(item) {
  const key = mediaKey(item);
  const local = Boolean(item.mediaUrl);
  const selected = state.selected.has(key);
  const source = local ? (item.kind === "preview" ? t("preview") : "LOCAL") : (item.siteLabel || item.site || "WEB");
  const secondary = local
    ? `${item.hasSubtitle ? t("subtitleReady") : t("noSubtitle")}`
    : [formatViews(item.views) && `${formatViews(item.views)} ${t("views")}`, item.uploader].filter(Boolean).join(" · ");
  const thumb = item.thumbnail
    ? `<img src="${escapeHtml(item.thumbnail)}" alt="" loading="lazy" referrerpolicy="no-referrer">`
    : "";
  return `
    <article class="media-card${selected ? " selected" : ""}" data-key="${escapeHtml(key)}">
      <div class="media-thumb">
        ${thumb}<span class="placeholder-mark">M</span>
        <button class="card-check" data-action="select-item" aria-label="${t("selected")}">✓</button>
        <span class="source-pill">${escapeHtml(source)}</span>
        <span class="duration-pill">${formatDuration(item.duration)}</span>
        <button class="play-button" data-action="play-item" aria-label="${t("preview")}">▶</button>
      </div>
      <div class="media-info">
        <h3 title="${escapeHtml(item.title)}">${escapeHtml(item.title)}</h3>
        <div class="media-info-row">
          <span>${escapeHtml(source)}</span>
          <span>${escapeHtml(secondary || t("unknown"))}</span>
        </div>
        <div class="card-actions">
          ${state.view !== "preview" && !local ? `<button data-action="card-preview">${t("addPreview")}</button>` : ""}
          ${state.view !== "queue" && !local ? `<button data-action="card-queue">${t("addQueue")}</button>` : ""}
          ${(state.view === "preview" || state.view === "queue") ? `<button data-action="card-remove">${t("remove")}</button>` : ""}
          ${local && item.subtitleUrl ? `<button data-action="play-item">${t("subtitleReady")}</button>` : ""}
        </div>
      </div>
    </article>
  `;
}

