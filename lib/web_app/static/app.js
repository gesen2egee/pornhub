function render() {
  const items = filteredItems();
  const hasAny = getCurrentItems().length > 0;
  $("#emptyState").hidden = hasAny;
  $("#loadingState").hidden = true;
  $("#mediaGrid").hidden = !hasAny;
  $("#mediaGrid").classList.toggle("compact", state.density === "compact");
  if (hasAny) {
    $("#mediaGrid").innerHTML = (state.view === "queue" ? queueHeaderHtml() : "") +
      (items.length ? items.map(cardHtml).join("") : `
        <div class="no-filter-results"><h2>${t("noItems")}</h2><p>${t("clearFilters")}</p></div>
      `);
    $$("#mediaGrid img").forEach(image => image.addEventListener("error", () => image.remove(), { once: true }));
  } else {
    $("#emptyState h2").textContent = state.view === "discover" ? t("emptyTitle") : t("noItems");
    $("#emptyState > p").textContent = state.view === "discover" ? t("emptyDescription") : t("noItemsNote");
    $(".quick-searches").hidden = state.view !== "discover";
  }
  updateCounts();
  updateSummary();
  updateBulkBar();
}

function updateCounts() {
  $("#previewCount").textContent = state.preview.length || "";
  $("#queueCount").textContent = state.queue.length || "";
  $("#previewTabCount").textContent = state.preview.length;
  $("#queueTabCount").textContent = state.queue.length;
}

function updateSummary() {
  const count = filteredItems().length;
  const units = {
    discover: t("results"), preview: t("previewItems"),
    queue: t("queueItems"), library: t("libraryItems")
  };
  $("#resultSummary").textContent = getCurrentItems().length ? `${count} ${units[state.view]}` : t("emptySummary");
}

function updateBulkBar() {
  $("#bulkBar").hidden = state.selected.size === 0;
  $("#selectedCount").textContent = state.selected.size;
}

function setView(view) {
  state.view = view;
  state.selected.clear();
  $$("[data-view]").forEach(button => {
    const active = button.dataset.view === view;
    button.classList.toggle("active", active);
    if (button.getAttribute("role") === "tab") button.setAttribute("aria-selected", String(active));
  });
  render();
}

async function runSearch() {
  const input = $("#searchInput");
  const query = input.value.trim();
  if (!query) {
    input.focus();
    return;
  }
  state.view = "discover";
  state.selected.clear();
  $("#emptyState").hidden = true;
  $("#mediaGrid").hidden = true;
  $("#loadingState").hidden = false;
  $$("[data-view]").forEach(button => button.classList.toggle("active", button.dataset.view === "discover"));
  state.history = [query, ...state.history.filter(item => item !== query)].slice(0, 8);
  persist();
  try {
    if (/^https?:\/\//i.test(query)) {
      state.results = [{
        id: query, url: query, title: query, siteLabel: new URL(query).hostname,
        duration: null, tags: [], thumbnail: "", views: null
      }];
    } else {
      const params = new URLSearchParams({
        q: query,
        sites: state.selectedSites.join(","),
        pages: $("#pageCount").value,
        limit: "48",
      });
      const payload = await api(`/api/search?${params}`);
      state.results = payload.results;
      if (payload.warnings?.length) showToast(t("sourceWarning"));
    }
    render();
  } catch (error) {
    $("#loadingState").hidden = true;
    $("#emptyState").hidden = false;
    showToast(`${t("searchFailed")}：${error.message}`, true);
  }
}

function findItem(key) {
  return [...state.results, ...state.preview, ...state.queue, ...state.library]
    .find(item => mediaKey(item) === key);
}

function addItem(target, item) {
  const collection = state[target];
  if (collection.some(existing => mediaKey(existing) === mediaKey(item))) {
    showToast(t("duplicate"));
    return;
  }
  collection.unshift(item);
  persist();
  showToast(target === "preview" ? t("addedPreview") : t("addedQueue"));
  render();
}

function removeItem(collection, item) {
  state[collection] = state[collection].filter(existing => mediaKey(existing) !== mediaKey(item));
  persist();
  render();
}

async function playItem(item) {
  state.currentPlayerItem = item;
  $("#playerTitle").textContent = item.title;
  $("#playerSource").textContent = item.siteLabel || item.site || (item.kind === "preview" ? t("preview") : "LOCAL");
  $("#sourceLink").href = item.url || "#";
  $("#videoPlayer").hidden = true;
  $("#playerFallback").hidden = true;
  $("#subtitleStatus").textContent = item.hasSubtitle ? t("subtitleReady") : t("noSubtitle");
  const dialog = $("#playerDialog");
  dialog.showModal();

  if (item.mediaUrl) {
    setupVideo(item.mediaUrl, item.subtitleUrl, item);
    return;
  }
  $("#playerFallback").hidden = false;
  $("#playerFallback p").textContent = t("directPlayback");
  try {
    const payload = await api("/api/resolve", {
      method: "POST", body: JSON.stringify({ url: item.url })
    });
    if (!payload.item.streamUrl) throw new Error("no stream");
    $("#playerFallback").hidden = true;
    setupVideo(payload.item.streamUrl, "", item);
  } catch {
    $("#playerFallback").hidden = false;
    $("#playerFallback p").textContent = t("remotePlaybackNote");
    showToast(t("playbackFailed"), true);
  }
}

function setupVideo(src, subtitleUrl, item) {
  const video = $("#videoPlayer");
  const track = $("#subtitleTrack");
  video.hidden = false;
  video.src = src;
  if (subtitleUrl) {
    track.src = subtitleUrl;
    track.default = state.autoSubtitle;
    track.addEventListener("load", () => {
      if (video.textTracks[0]) video.textTracks[0].mode = state.autoSubtitle ? "showing" : "hidden";
    }, { once: true });
  } else {
    track.removeAttribute("src");
  }
  const progressKey = `muse-progress:${mediaKey(item)}`;
  video.onloadedmetadata = () => {
    if (state.rememberProgress) {
      const savedProgress = Number(localStorage.getItem(progressKey) || 0);
      if (savedProgress > 2 && savedProgress < video.duration - 5) video.currentTime = savedProgress;
    }
  };
  video.ontimeupdate = () => {
    if (state.rememberProgress && Math.floor(video.currentTime) % 5 === 0) {
      localStorage.setItem(progressKey, String(video.currentTime));
    }
  };
  video.onerror = () => {
    video.hidden = true;
    $("#playerFallback").hidden = false;
    $("#playerFallback p").textContent = item.mediaUrl ? t("playbackFailed") : t("remotePlaybackNote");
  };
  video.play().catch(() => {});
}

function closePlayer() {
  const video = $("#videoPlayer");
  video.pause();
  video.removeAttribute("src");
  video.load();
  $("#playerDialog").close();
}

async function startQueueTask(kind) {
  try {
    if (kind === "download") {
      await api("/api/download/start", { method: "POST", body: "{}" });
    } else {
      await api("/api/queue", {
        method: "POST",
        body: JSON.stringify({ items: state.queue, quality: kind }),
      });
    }
    showToast(t("queueStarted"));
    pollTasks();
  } catch (error) {
    showToast(error.message, true);
  }
}

let taskTimer = null;
async function pollTasks() {
  clearTimeout(taskTimer);
  try {
    const { tasks } = await api("/api/tasks");
    const active = tasks.find(task => ["queued", "running"].includes(task.state));
    const recent = tasks[0];
    if (recent && ["ready", "done", "failed"].includes(recent.state) && !recent.notified) {
      showToast(recent.message, recent.state === "failed");
    }
    if (active) taskTimer = setTimeout(pollTasks, 3000);
    else {
      const library = await api("/api/library");
      state.library = library.items;
      if (state.view === "library") render();
    }
  } catch {}
}

function handleCardAction(action, item) {
  if (!item) return;
  if (action === "select-item") {
    const key = mediaKey(item);
    state.selected.has(key) ? state.selected.delete(key) : state.selected.add(key);
    render();
  } else if (action === "play-item") playItem(item);
  else if (action === "card-preview") addItem("preview", item);
  else if (action === "card-queue") addItem("queue", item);
  else if (action === "card-remove") removeItem(state.view, item);
}

function renderFilters() {
  const labels = [];
  if (state.durationFilter !== "all") labels.push(`${t("duration")}: ${state.durationFilter}`);
  if (state.withinQuery) labels.push(`${t("filterKeyword")}: ${state.withinQuery}`);
  if (state.sourceFilter !== "all") labels.push(`${t("source")}: ${state.sourceFilter}`);
  if (state.subtitleOnly) labels.push(t("hasSubtitle"));
  if (state.hideUnknown) labels.push(t("hideUnknown"));
  $("#activeFilters").hidden = labels.length === 0;
  $("#activeFilters").innerHTML = labels.map(label => `<span class="active-filter">${escapeHtml(label)}</span>`).join("");
  $("#filterCount").hidden = labels.length === 0;
  $("#filterCount").textContent = labels.length;
  render();
}

function bindEvents() {
  document.addEventListener("click", event => {
    const actionNode = event.target.closest("[data-action]");
    const viewNode = event.target.closest("[data-view]");
    if (viewNode) setView(viewNode.dataset.view);
    if (!actionNode) return;
    const action = actionNode.dataset.action;
    const card = actionNode.closest(".media-card");
    const item = card ? findItem(card.dataset.key) : null;
    if (card) {
      handleCardAction(action, item);
      return;
    }
    const actions = {
      search: runSearch,
      "site-picker": () => {
        $("#sitePicker").hidden = !$("#sitePicker").hidden;
        actionNode.setAttribute("aria-expanded", String(!$("#sitePicker").hidden));
      },
      "recommended-sites": () => {
        state.selectedSites = state.sites.filter(site => site.recommended).map(site => site.id);
        renderSitePicker();
        persist();
      },
      locale: () => { state.locale = state.locale === "zh" ? "en" : "zh"; persist(); applyLocale(); updateSiteSummary(); },
      theme: () => { state.theme = state.theme === "dark" ? "light" : "dark"; persist(); applyPreferences(); },
      "toggle-blur": () => { state.blur = !state.blur; persist(); applyPreferences(); },
      settings: () => $("#settingsDialog").showModal(),
      "close-settings": () => $("#settingsDialog").close(),
      filters: () => {
        $("#filterPanel").hidden = !$("#filterPanel").hidden;
        actionNode.setAttribute("aria-expanded", String(!$("#filterPanel").hidden));
      },
      "clear-filters": () => {
        state.durationFilter = "all"; state.subtitleOnly = false; state.hideUnknown = false;
        state.withinQuery = ""; state.sourceFilter = "all";
        $("#subtitleOnly").checked = false; $("#hideUnknown").checked = false;
        $("#withinQuery").value = ""; $("#sourceFilter").value = "all";
        $$("#durationChips button").forEach(button => button.classList.toggle("active", button.dataset.duration === "all"));
        renderFilters();
      },
      "clear-selection": () => { state.selected.clear(); render(); },
      "move-preview": () => {
        [...state.selected].map(findItem).filter(Boolean).forEach(item => addItem("preview", item));
        state.selected.clear(); render();
      },
      "move-queue": () => {
        [...state.selected].map(findItem).filter(Boolean).forEach(item => addItem("queue", item));
        state.selected.clear(); render();
      },
      "close-player": closePlayer,
      "dialog-preview": () => { if (state.currentPlayerItem) addItem("preview", state.currentPlayerItem); },
      "dialog-queue": () => { if (state.currentPlayerItem) addItem("queue", state.currentPlayerItem); },
      "privacy-off": () => { $("#privacyScreen").hidden = true; },
      "capture-preview": () => startQueueTask("preview"),
      "capture-full": () => startQueueTask("full"),
      "start-download": () => startQueueTask("download"),
    };
    actions[action]?.();
  });

  $("#searchInput").addEventListener("keydown", event => {
    if (event.key === "Enter") runSearch();
  });
  $(".quick-searches").addEventListener("click", event => {
    const button = event.target.closest("[data-query]");
    if (!button) return;
    $("#searchInput").value = button.dataset.query;
    runSearch();
  });
  $("#sortSelect").addEventListener("change", event => { state.sort = event.target.value; render(); });
  $$(".density-control button").forEach(button => button.addEventListener("click", () => {
    state.density = button.dataset.density;
    $$(".density-control button").forEach(item => item.classList.toggle("active", item === button));
    render();
  }));
  $$("#durationChips button").forEach(button => button.addEventListener("click", () => {
    state.durationFilter = button.dataset.duration;
    $$("#durationChips button").forEach(item => item.classList.toggle("active", item === button));
    renderFilters();
  }));
  $("#subtitleOnly").addEventListener("change", event => { state.subtitleOnly = event.target.checked; renderFilters(); });
  $("#hideUnknown").addEventListener("change", event => { state.hideUnknown = event.target.checked; renderFilters(); });
  $("#withinQuery").addEventListener("input", event => { state.withinQuery = event.target.value.trim(); renderFilters(); });
  $("#sourceFilter").addEventListener("change", event => { state.sourceFilter = event.target.value; renderFilters(); });
  $("#blurSetting").addEventListener("change", event => { state.blur = event.target.checked; persist(); applyPreferences(); });
  $("#progressSetting").addEventListener("change", event => { state.rememberProgress = event.target.checked; persist(); });
  $("#subtitleSetting").addEventListener("change", event => { state.autoSubtitle = event.target.checked; persist(); });
  $("#playerDialog").addEventListener("cancel", event => { event.preventDefault(); closePlayer(); });
  document.addEventListener("keydown", event => {
    if (event.key === "/" && !["INPUT", "TEXTAREA"].includes(document.activeElement.tagName)) {
      event.preventDefault(); $("#searchInput").focus();
    }
    if ((event.key === "p" || event.key === "P") && !["INPUT", "TEXTAREA"].includes(document.activeElement.tagName)) {
      $("#privacyScreen").hidden = !$("#privacyScreen").hidden;
    }
    if (event.key === "Escape" && !$("#privacyScreen").hidden) $("#privacyScreen").hidden = true;
  });
}

